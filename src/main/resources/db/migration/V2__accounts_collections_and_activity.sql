CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(512) NOT NULL,
 display_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK(role IN ('USER','ADMIN')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE genre (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE person (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(200) NOT NULL);
CREATE INDEX person_name_idx ON person(name);
CREATE TABLE movie_genre (
 movie_id BIGINT REFERENCES "movies"("ID") ON DELETE CASCADE,
 genre_id BIGINT REFERENCES genre(id), PRIMARY KEY(movie_id,genre_id)
);
CREATE TABLE movie_credit (
 movie_id BIGINT REFERENCES "movies"("ID") ON DELETE CASCADE,
 person_id BIGINT REFERENCES person(id), role VARCHAR(20) NOT NULL CHECK(role IN ('CAST','DIRECTOR')),
 PRIMARY KEY(movie_id,person_id,role)
);
CREATE INDEX credit_person_idx ON movie_credit(person_id,role,movie_id);
CREATE INDEX genre_movie_idx ON movie_genre(genre_id,movie_id);
INSERT INTO genre(name) SELECT DISTINCT "GENRE" FROM "movies";
INSERT INTO movie_genre(movie_id,genre_id) SELECT m."ID",g.id FROM "movies" m JOIN genre g ON g.name=m."GENRE";
INSERT INTO person(name) SELECT DISTINCT "DIRECTOR" FROM "movies";
INSERT INTO movie_credit(movie_id,person_id,role) SELECT m."ID",p.id,'DIRECTOR' FROM "movies" m JOIN person p ON p.name=m."DIRECTOR";
CREATE TABLE external_rating (
 movie_id BIGINT REFERENCES "movies"("ID") ON DELETE CASCADE,
 source VARCHAR(80) NOT NULL, score DOUBLE PRECISION NOT NULL CHECK(score>=0),
 scale_max DOUBLE PRECISION NOT NULL CHECK(scale_max>0), vote_count BIGINT CHECK(vote_count>=0),
 fetched_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(movie_id,source), CHECK(score<=scale_max)
);
CREATE TABLE user_collection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id), name VARCHAR(120) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX collection_owner_idx ON user_collection(user_id,id);
CREATE TABLE collection_item (
 collection_id BIGINT REFERENCES user_collection(id) ON DELETE CASCADE,
 movie_id BIGINT REFERENCES "movies"("ID") ON DELETE CASCADE,
 added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(collection_id,movie_id)
);
CREATE TABLE personal_rating (
 user_id BIGINT REFERENCES app_user(id), movie_id BIGINT REFERENCES "movies"("ID") ON DELETE CASCADE,
 score INTEGER NOT NULL CHECK(score BETWEEN 1 AND 5),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,movie_id)
);
CREATE TABLE collection_share (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 collection_id BIGINT NOT NULL REFERENCES user_collection(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMP WITH TIME ZONE,
 revoked_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE audit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_user_id BIGINT REFERENCES app_user(id), action VARCHAR(80) NOT NULL,
 resource_type VARCHAR(40) NOT NULL, resource_id VARCHAR(100), outcome VARCHAR(20) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 correlation_id VARCHAR(36) NOT NULL
);
CREATE INDEX audit_owner_time_idx ON audit_event(actor_user_id,occurred_at,id);
CREATE TABLE analytics_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id VARCHAR(36) NOT NULL UNIQUE,
 user_id BIGINT NOT NULL REFERENCES app_user(id), event_name VARCHAR(80) NOT NULL,
 movie_id BIGINT, journey_id VARCHAR(36),
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX analytics_name_time_idx ON analytics_event(event_name,occurred_at);
CREATE TABLE ai_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id), request_type VARCHAR(30) NOT NULL,
 engine VARCHAR(100) NOT NULL, fallback_used BOOLEAN NOT NULL,
 result_count INTEGER NOT NULL, latency_ms BIGINT NOT NULL,
 correlation_id VARCHAR(36) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
